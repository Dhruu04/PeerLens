/**
 * Returns the diverse 100 students dataset formatted as standard CSV text.
 */
export function getSampleStudentsCSV(): string {
  const headers = [
    "Student ID",
    "Full Name",
    "Email",
    "Group / Team",
    "Gender",
    "Nationality",
    "English Level",
    "University",
    "Degree",
    "Student Type"
  ];

  const rows = DIVERSE_100_STUDENTS.map(s => [
    `"${s.id}"`,
    `"${s.name}"`,
    `"${s.email}"`,
    `"${s.groupName || 'Unassigned'}"`,
    `"${s.gender || 'Prefer not to say'}"`,
    `"${s.nationality || ''}"`,
    `"${s.englishProficiency || 'Fluent (C1/C2)'}"`,
    `"${s.university || ''}"`,
    `"${s.degree || ''}"`,
    `"${s.studentType || 'Normal'}"`
  ].join(","));

  return [headers.join(","), ...rows].join("\n");
}

/**
 * Triggers a client-side file download of the sample dataset in CSV, Excel (.xlsx), or JSON format.
 */
export function downloadSampleStudentsFile(format: 'csv' | 'xlsx' | 'json' = 'csv') {
  if (format === 'csv') {
    const csvContent = getSampleStudentsCSV();
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', 'diverse_100_students_sample.csv');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  } else if (format === 'xlsx') {
    const data = DIVERSE_100_STUDENTS.map(s => ({
      "Student ID": s.id,
      "Full Name": s.name,
      "Email": s.email,
      "Group / Team": s.groupName,
      "Gender": s.gender,
      "Nationality": s.nationality,
      "English Level": s.englishProficiency,
      "University": s.university,
      "Degree": s.degree,
      "Student Type": s.studentType
    }));

    const ws = XLSX.utils.json_to_sheet(data);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, "Diverse 100 Students");
    XLSX.writeFile(wb, "diverse_100_students_sample.xlsx");
  } else if (format === 'json') {
    const jsonContent = JSON.stringify(DIVERSE_100_STUDENTS, null, 2);
    const blob = new Blob([jsonContent], { type: 'application/json;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', 'diverse_100_students_sample.json');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }
}
