export function getSampleStudentsCSV(): string {
  const headers = [
    'Student ID',
    'Full Name',
    'Email Address',
    'Group / Team Name',
    'University / College',
    'Degree / Major',
    'Student Status',
    'Exchange Student?',
    'Original Country (Home)',
    'Original University (Home)',
    'Current Country (Host)',
    'Current University (Host)',
    'Gender',
    'Nationality / Country',
    'English Proficiency'
  ];

  const rows = DIVERSE_100_STUDENTS.map((s) => [
    `"${s.id}"`,
    `"${s.name}"`,
    `"${s.email}"`,
    `"${s.groupName}"`,
    `"${s.university || s.currentUniversity || ''}"`,
    `"${s.degree || ''}"`,
    `"${s.studentType || 'Normal'}"`,
    `"${s.isExchange ? 'Yes' : 'No'}"`,
    `"${s.originalCountry || s.nationality || ''}"`,
    `"${s.originalUniversity || s.university || ''}"`,
    `"${s.currentCountry || s.nationality || ''}"`,
    `"${s.currentUniversity || s.university || ''}"`,
    `"${s.gender || 'Female'}"`,
    `"${s.nationality || ''}"`,
    `"${s.englishProficiency || 'Fluent (C1/C2)'}"`
  ]);

  return [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
}

export function generateSampleStudentsExcel(): void {
  const wb = XLSX.utils.book_new();

  const headers = [
    'Student ID',
    'Full Name',
    'Email Address',
    'Group / Team Name',
    'University / College',
    'Degree / Major',
    'Student Status',
    'Exchange Student?',
    'Original Country (Home)',
    'Original University (Home)',
    'Current Country (Host)',
    'Current University (Host)',
    'Gender',
    'Nationality / Country',
    'English Proficiency'
  ];

  const rows = DIVERSE_100_STUDENTS.map((s) => [
    s.id,
    s.name,
    s.email,
    s.groupName,
    s.university || s.currentUniversity || 'N/A',
    s.degree || 'N/A',
    s.studentType || 'Normal',
    s.isExchange ? 'Yes' : 'No',
    s.originalCountry || s.nationality || 'N/A',
    s.originalUniversity || s.university || 'N/A',
    s.currentCountry || s.nationality || 'N/A',
    s.currentUniversity || s.university || 'N/A',
    s.gender || 'Prefer not to say',
    s.nationality || 'N/A',
    s.englishProficiency || 'Fluent (C1/C2)'
  ]);

  const ws = XLSX.utils.aoa_to_sheet([headers, ...rows]);
  XLSX.utils.book_append_sheet(wb, ws, 'Diverse 100 Classroom');
  XLSX.writeFile(wb, 'PeerEvaluation_100_Diverse_Students_Sample.xlsx');
}

export function downloadSampleStudentsFile(format: 'csv' | 'xlsx'): void {
  if (format === 'xlsx') {
    generateSampleStudentsExcel();
    return;
  }
  const csvContent = getSampleStudentsCSV();
  const blob = new Blob(['\uFEFF' + csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', 'PeerEvaluation_100_Diverse_Students_Sample.csv');
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

